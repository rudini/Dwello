import { describe, expect, it } from 'vitest';
import { analyze } from '../src/analyze.ts';
import { DEEP_MODULE, SHALLOW_MODULE, writeProject } from './helpers.ts';

const root = writeProject({
	'src/deep.ts': DEEP_MODULE,
	'src/shallow.ts': SHALLOW_MODULE,
	'src/store.ts': 'export const store = new Map<string, string>();\n',
	'src/index.ts': "export * from './deep';\nexport { getName } from './shallow';\n",
	'src/dto.ts': 'export interface Tenant {\n\tname: string;\n}\nexport type TenantId = string;\n',
	'src/clamp.ts':
		'export function clamp(value: number, min: number, max: number): number {\n\treturn Math.min(max, Math.max(min, value));\n}\n',
	'src/deep.test.ts': "import { parseCsv } from './deep';\nparseCsv('a');\n",
	'src/__tests__/x.ts': 'export const x = 1;\n',
	'tools/lib/test/helpers.ts': 'export const helper = 1;\n',
	'src/routes/edit/+page.server.ts': "import { getName } from '../../shallow';\nexport const load = ({ id }: { id: string }) => ({ name: getName(id) });\nexport const actions = { default: () => getName('x') };\n",
	'src/hooks.server.ts': 'export const handle = ({ event, resolve }: { event: unknown; resolve: (e: unknown) => unknown }) => resolve(event);\n',
	'vite.config.ts': 'export default { plugins: [] };\n',
	'src/env.d.ts': 'declare const VERSION: string;\n',
	'src/generated/client.ts': 'export function call(a: string) {\n\treturn fetch(a);\n}\n',
	'src/api.gen.ts': '// @generated by a tool, do not edit\nexport function call(a: string) {\n\treturn fetch(a);\n}\n'
});
const report = analyze({ root, fallow: 'off' });
const module = (path: string) => report.modules.find((m) => m.path === path);

describe('metrics', () => {
	it('scores a shallow module higher than a deep one', () => {
		expect(module('src/shallow.ts')!.score).toBeGreaterThan(module('src/deep.ts')!.score);
	});

	it('measures the interface and implementation of the deep module', () => {
		const deep = module('src/deep.ts')!.metrics;
		// one exported function with one parameter
		expect(deep.interfaceSize).toBe(2);
		expect(deep.implementationSize).toBeGreaterThan(20);
		expect(deep.depthRatio).toBe(deep.implementationSize / 2);
	});

	it('detects each pass-through with its location', () => {
		const lines = module('src/shallow.ts')!.metrics.passThroughs.map((p) => `${p.name}:${p.line}`);
		expect(lines).toEqual(['getName:4', 'setName:7', 'hasName:10', 'deleteName:13']);
	});

	it('flags the shallow module but not the deep one', () => {
		expect(module('src/shallow.ts')!.flagged).toBe(true);
		expect(module('src/deep.ts')!.flagged).toBe(false);
	});

	it('does not flag a tiny utility below the minimum interface size', () => {
		expect(module('src/clamp.ts')!.flagged).toBe(false);
	});

	it('excludes tests, declarations, generated files, framework entries, type-only files and barrels', () => {
		expect(report.excluded).toEqual([
			{ path: 'src/__tests__/x.ts', reason: 'test' },
			{ path: 'src/api.gen.ts', reason: 'generated' },
			{ path: 'src/deep.test.ts', reason: 'test' },
			{ path: 'src/dto.ts', reason: 'type-only' },
			{ path: 'src/env.d.ts', reason: 'declaration' },
			{ path: 'src/generated/client.ts', reason: 'generated' },
			{ path: 'src/hooks.server.ts', reason: 'entry' },
			{ path: 'src/index.ts', reason: 'barrel' },
			{ path: 'src/routes/edit/+page.server.ts', reason: 'entry' },
			{ path: 'tools/lib/test/helpers.ts', reason: 'test' },
			{ path: 'vite.config.ts', reason: 'entry' }
		]);
		expect(report.modules.map((m) => m.path)).toEqual(
			expect.not.arrayContaining(['src/index.ts', 'src/dto.ts'])
		);
	});

	it('orders modules by score, then path', () => {
		const scores = report.modules.map((m) => m.score);
		expect(scores).toEqual([...scores].sort((a, b) => b - a));
	});
});
